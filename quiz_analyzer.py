scores = []
scores.append(int(input("Enter 1st quiz score: ")))
scores.append(int(input("Enter 2nd quiz score: ")))
scores.append(int(input("Enter 3rd quiz score: ")))
scores.append(int(input("Enter 4th quiz score: ")))
scores.append(int(input("Enter 5th quiz score: ")))

total = sum(scores)
average = total / len(scores)
ceiling = max(scores)
floor = min(scores)
ascending = sorted(scores)
descending = sorted(scores, reverse=True)

print()
print("===== QUIZ SCORE REPORT =====")
print(f"Quiz Scores: {scores}")
print("Number of quizzes: 5")
print(f"Total score: {total}")
print(f"Average score: {average:.2f}")
print(f"Highest score: {ceiling}")
print(f"Lowest score: {floor}")
print(f"Ascending score: {ascending}")
print(f"Descending score: {descending}")
print(f"Original scores: {scores}")